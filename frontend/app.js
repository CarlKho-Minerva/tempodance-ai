function clonePose(pose) {
  return pose.map(([x, y]) => [x, y]);
}

function clamp(value, min = 0, max = 1) {
  return Math.max(min, Math.min(max, value));
}

function lerp(a, b, t) {
  return a + (b - a) * t;
}

function smoothstep(t) {
  return t * t * (3 - 2 * t);
}

function formatTime(milliseconds) {
  const total = Math.floor(milliseconds / 1000);
  return `${String(Math.floor(total / 60)).padStart(2, "0")}:${String(total % 60).padStart(2, "0")}`;
}

function formatPlaybackSpeed(speed) {
  return `${Number(speed).toFixed(speed < .5 ? 2 : 1)}×`;
}

function getReferencePose(phase) {
  const keyframes = state.routineKeyframes;
  const position = phase * keyframes.length;
  const index = Math.floor(position) % keyframes.length;
  const nextIndex = (index + 1) % keyframes.length;
  const amount = smoothstep(position - Math.floor(position));
  return keyframes[index].map(([x, y], joint) => [
    lerp(x, keyframes[nextIndex][joint][0], amount),
    lerp(y, keyframes[nextIndex][joint][1], amount),
  ]);
}

async function loadSourceMotion() {
  try {
    const response = await fetch(SOURCE_POSE_PATH);
    if (!response.ok) throw new Error(`Pose track failed (${response.status})`);
    const payload = await response.json();
    const poses = payload.poses?.filter((pose) => Array.isArray(pose) && pose.length >= 17);
    if (!poses || poses.length < 8) throw new Error("Pose track is incomplete");
    state.routineKeyframes = poses;
    state.sourceDuration = Number(payload.duration) || SOURCE_DURATION_SECONDS;
    state.sourceBeats = Array.isArray(payload.beats) ? payload.beats.map(Number).filter(Number.isFinite) : [];
    state.detectedBpm = Number(payload.detected_bpm) || 90;
    elements.routineBpm.textContent = String(Math.round(state.detectedBpm));
    state.sourceMotionReady = true;
    elements.sourceBadge.innerHTML = "<i></i> ML track ready";
  } catch {
    state.sourceMotionReady = false;
    elements.sourceBadge.innerHTML = "<i></i> ML track unavailable";
    showBanner("The local pose track could not load, so scoring and the coach overlay are paused instead of showing mismatched motion.");
  }
}

