function tick(now) {
  const delta = Math.min(now - state.lastFrameAt, 100);
  state.lastFrameAt = now;

  if (state.playing) {
    state.elapsedPlayingMs += delta;
    const speed = SPEEDS[state.speedIndex];
    const previousPhase = state.phase;
    const sourceDuration = elements.referenceVideo.duration || state.sourceDuration;
    if (elements.referenceVideo.readyState >= HTMLMediaElement.HAVE_CURRENT_DATA && sourceDuration > 0) {
      const sourceTime = elements.referenceVideo.currentTime;
      state.phase = clamp(sourceTime / sourceDuration);
      if (sourceTime + .25 < state.previousSourceTime) state.currentBeatIndex = -1;
      if (state.sourceBeats.length) {
        const beatIndex = state.sourceBeats.findLastIndex((beat) => beat <= sourceTime + .015);
        if (beatIndex >= 0) {
          const previousBeatIndex = state.currentBeatIndex;
          const beatStart = state.sourceBeats[beatIndex];
          const beatEnd = state.sourceBeats[beatIndex + 1] ?? beatStart + 60 / state.detectedBpm;
          const beatProgress = clamp((sourceTime - beatStart) / (beatEnd - beatStart));
          state.currentCount = (beatIndex % 8) + 1;
          state.countPhase = ((beatIndex % 8) + beatProgress) / 8;
          if (previousBeatIndex >= 0 && Math.floor(beatIndex / 8) > Math.floor(previousBeatIndex / 8)) handleCompletedLoop();
          state.currentBeatIndex = beatIndex;
        } else {
          state.currentCount = 1;
          state.countPhase = 0;
        }
      } else {
        state.currentCount = Math.min(8, Math.floor(state.phase * 8) + 1);
        state.countPhase = state.phase;
      }
      state.previousSourceTime = sourceTime;
    } else {
      const loopDuration = (state.sourceDuration * 1000) / speed;
      state.phase = (state.phase + delta / loopDuration) % 1;
      if (state.phase < previousPhase) handleCompletedLoop();
      state.currentCount = Math.min(8, Math.floor(state.phase * 8) + 1);
      state.countPhase = state.phase;
    }
    state.loopMinimum = Math.min(state.loopMinimum, state.score ?? 1);
    elements.transportTitle.textContent = `Loop ${state.completedLoops + 1} · count ${state.currentCount}`;
    elements.sessionClock.textContent = formatTime(state.elapsedPlayingMs);
  }

  if (!state.sourceMotionReady) {
    clearCanvas(elements.referenceCanvas);
    clearCanvas(elements.liveCanvas);
    updateCountUI();
    updateTimingUI();
    requestAnimationFrame(tick);
    return;
  }

  state.latestReference = getReferencePose(state.phase);
  const trailOffset = 1 / state.routineKeyframes.length;
  const trailReference = getReferencePose((state.phase - trailOffset + 1) % 1);
  renderSkeleton(elements.referenceCanvas, state.latestReference, {
    primary: "#a98aff",
    trailPose: trailReference,
    focus: state.focus,
    sourceAspect: SOURCE_ASPECT_RATIO,
  });

  if (state.mode === "demo") {
    state.latestLive = createDemoPose(state.latestReference, now);
    const learningPenalty = state.playing ? lerp(.075, .008, clamp(state.elapsedPlayingMs / 7000)) : .075;
    const result = calculatePoseScore(state.latestLive, state.latestReference, learningPenalty);
    state.score = state.playing ? result.score : state.score;
    state.boneScores = result.boneScores;
    renderSkeleton(elements.liveCanvas, state.latestLive, {
      primary: "#b7ff5a",
      feedback: true,
      boneScores: state.boneScores,
      trailPose: createDemoPose(getReferencePose((state.phase - trailOffset + 1) % 1), now - 35),
      focus: state.focus,
    });
  } else if (state.serverPose) {
    state.latestLive = state.serverPose;
    if (!Number.isFinite(state.score) || !Object.keys(state.boneScores).length) {
      const localResult = calculatePoseScore(state.serverPose, state.latestReference);
      state.score = localResult.score;
      state.boneScores = localResult.boneScores;
    }
    renderSkeleton(elements.liveCanvas, state.serverPose, { primary: "#b7ff5a", feedback: true, boneScores: state.boneScores, focus: state.focus });
  } else {
    clearCanvas(elements.liveCanvas);
  }

  updateCountUI();
  updateScoreUI();
  updateTimingUI(now);
  updateAgentUI();
  updateChart(now);

  if (state.playing && now - state.lastObservationAt > 150) {
    state.lastObservationAt = now;
    postObservation();
  }
  if (state.mode === "camera") sendCameraFrame(now);
  requestAnimationFrame(tick);
}

